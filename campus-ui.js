function getRoomCategory(rm, lm) {
  const code = rm.code || '';
  const name = rm.name || '';
  const lmId = lm?.id || '';
  if (lmId === 'new-building' || code.startsWith('K') || code === 'S1-KOFF' || /幼兒園/.test(name)) return '幼兒園';
  if (/[一二三四五六]年級| (10[1-3]|20[1-4]|30[1-3]|40[1-4]|50[1-4]|60[1-4]) /.test(name)) return '班級';
  if (['11', '21', '12', '13', '14', '71'].includes(code) || /校長室|人事室|教務處|學務處|總務處|輔導室/.test(name)) return '行政';
  if (code === '74' || /儲藏室/.test(name)) return '其他';
  if (['20', '32', '36', '30', '40', '72', '73', 'S2-KACT', 'S3-KACT', '42', '45', 'B1-W'].includes(code) ||
      /健康中心|保健室|圖書室|共讀站|視聽教室|展演廳|會議室|課照[34]|閱讀室|活動室|柑仔店|防空避難室/.test(name)) return '公共';
  if (['41', '43', '46', '47', '44', '48', '49', '45-M', '65', '63', '62', '70', '64', '35', '33', '38', '37', '76'].includes(code) ||
      /自然|英語|社會|美術|音樂|電腦|數位學習|巡輔|資源班|多功能|體育室|體適能/.test(name)) return '專科';
  return '公共';
}

function getLandmarkCategories(lm) {
  const cats = [];
  const id = lm.id;
  if (FEATURED_IDS.includes(id)) cats.push('featured');
  cats.push('all');
  if (['north-building', 'south-building'].includes(id)) cats.push('班級');
  if (['west-building'].includes(id)) cats.push('專科');
  if (['east-building'].includes(id)) cats.push('行政');
  if (['courtyard-plaza', 'breezeway-hub', 'playground-zone', 'east-south-mosaic'].includes(id)) cats.push('公共');
  if (['new-building'].includes(id)) cats.push('幼兒園');
  if (['command-stage', 'carport', 'organic-farm', 'recycling-depot'].includes(id)) cats.push('其他');
  if (['sports-track', 'ball-courts', 'command-stage'].includes(id)) cats.push('運動');
  if (['main-gate', 'east-gate', 'west-back-gate', 'stage-back-gate', 'new-south-gate', 'old-south-gate'].includes(id)) cats.push('出入口');
  return cats;
}

